def solution(cap, n, deliveries, pickups):
    ## 트럭은 항상 물류창고(0번 지점)에서 출발해 돌아와야 하므로
    ## 한 번의 왕복 비용은 "그 왕복에서 가장 멀리 간 집까지의 거리 x 2"로 고정된다.
    ## 배달과 수거는 같은 왕복 안에서 함께 처리해도 추가 비용이 없다.
    ## -> 가장 먼 집부터 역순으로 훑으면서, 그 집을 처리하는 데 필요한 왕복 횟수만 세면 된다.

    ## 남은 물량을 음수로 관리한다.
    ## 음수면 아직 처리하지 못한 상자가 남은 것이고, 양수면 이번 왕복에서 쓰고 남은 여유 적재량이다.

    answer = 0
    d_rest = 0  # 배달 여유 적재량 (음수면 배달하지 못하고 남은 상자 수)
    p_rest = 0  # 수거 여유 적재량 (음수면 수거하지 못하고 남은 상자 수)

    # 1. 물류창고에서 먼 집부터 역순으로 순회
    for house in range(n - 1, -1, -1):

        # 1-1. 이 집의 물량을 여유 적재량에서 차감
        d_rest -= deliveries[house]
        p_rest -= pickups[house]

        # 1-2. 배달이든 수거든 남은 물량이 있으면 이 집까지 왕복해야 함
        trip = 0
        while d_rest < 0 or p_rest < 0:
            trip += 1
            # 왕복 한 번마다 배달과 수거 모두 cap만큼 여유가 생김
            d_rest += cap
            p_rest += cap

        # 1-3. 이 집이 그 왕복들에서 가장 먼 집이므로 (house + 1) * 2 가 왕복 거리
        answer += trip * (house + 1) * 2

    return answer
