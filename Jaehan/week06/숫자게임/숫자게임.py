def solution(A, B):
    ## A와 B는 각각 n장의 카드를 가지고, 매 라운드마다 한 장씩 낸다.
    ## B가 낸 카드가 A가 낸 카드보다 클 때만 B가 1점을 얻는다.
    ## A가 내는 순서는 이미 정해져 있고, B는 순서를 마음대로 정할 수 있으므로
    ## "B의 카드 하나로 A의 카드 하나를 이기게 짝지어주는" 문제로 바뀐다.
    ## 이때 이길 수 있는 A의 카드 중 가장 큰 것을 잡아야 작은 카드가 남아 뒤에서 쓰기 좋다.
    ## 양쪽을 오름차순으로 정렬해두면 이 판단을 포인터 하나로 할 수 있다.

    # 양쪽 모두 오름차순 정렬 (A가 내는 순서는 점수에 영향을 주지 않으므로 정렬해도 된다)
    A.sort()
    B.sort()

    # B가 얻은 점수
    answer = 0

    # 아직 상대해주지 않은 A의 카드 중 가장 작은 카드의 위치
    a_idx = 0

    # B의 카드를 작은 것부터 꺼내면서 A의 남은 카드 중 가장 작은 것과 비교한다.
    for b in B:

        # A의 가장 작은 카드마저 이기지 못한다면 이 카드로는 아무도 이길 수 없다.
        # 그냥 버리는 카드로 쓰고 넘어간다. (a_idx는 그대로 둔다)
        if b > A[a_idx]:

            # 이겼으므로 점수를 얻고, 상대한 A의 카드는 소진 처리한다.
            answer += 1
            a_idx += 1

    return answer
